let cache: Set<string> | null = null;

function loadFromWordlist(): string[] {
  const raw = readFileSync(WORDLIST_PATH, 'utf-8');
  return raw
    .split('\n')
    .map((w) => stripDiacritics(w.trim().toLowerCase()))
    .filter((w) => w.length >= 3);
}

export function getBoggleWordSet(): Set<string> {
  if (cache) return cache;
  const words = new Set<string>();
  for (const w of loadFromWordlist()) words.add(w);
  for (const w of SHORT_WORDS) words.add(stripDiacritics(w.toLowerCase()));
  cache = words;
  return cache;
}
